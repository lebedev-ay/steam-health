-- Загрузка отзывов становится инкрементальной, и ей нужна отметка о том, из какой порции сырья пришла строка.
-- Максимум по этой колонке служит водяным знаком, поэтому отдельная таблица-счётчик не заводится: разойтись с фактами ей негде.
alter table core.fct_review add column loaded_from timestamptz;

-- Существующим строкам ставится самый ранний fetched_at из raw, а не now(): now() объявил бы загруженным всё сырьё целиком,
-- включая страницы, которые собраны, но в ядро не попали, и такие отзывы были бы пропущены навсегда.
-- Цена выбора разовая - первый инкрементальный прогон один раз перечитает весь raw и проставит настоящие границы.
update core.fct_review
set loaded_from = (select min(fetched_at) from raw.reviews);

comment on column core.fct_review.loaded_from is
    'fetched_at страницы raw.reviews, из которой взята строка. '
    'Максимум по колонке - водяной знак инкрементальной загрузки. '
    'NULL - порция неизвестна, при подсчёте водяного знака такие строки не учитываются';
