-- Зерно fct_patch - пара «событие - игра», а не одно событие. Одна
-- новость Steam может относиться к нескольким играм, и для каждой она
-- свой факт: своё окно относительно её отзывов и свой вес относительно
-- её медианы длины патчноута. Прежний уникальный ключ по одному gid
-- держал такую заметку единственной строкой, а game_sk у неё доставался
-- от того прогона, который записал её последним, то есть зависел от
-- порядка обхода игр и был недетерминирован.
--
-- Мостовая таблица здесь не нужна: тексты лежат в raw.news, в fct_patch
-- от них используется только body_length, и цена нового зерна - дубли
-- строк у 53 событий из 13360.
--
-- Существующие строки не пересоздаются: у остальных событий игра одна
-- и привязка верна. Недостающие строки для многоигровых заметок
-- допишет load_fct_patch.py на следующем прогоне - это его работа,
-- а не миграции. Старый ключ строго сильнее нового, поэтому текущие
-- данные проходят новое ограничение без конфликтов.
alter table core.fct_patch drop constraint fct_patch_gid_key;

alter table core.fct_patch
    add constraint ux_fct_patch_gid_game unique (gid, game_sk);
